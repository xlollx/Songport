#!/usr/bin/env python3
"""Brand strings for the Google Play flavour.

On Google Play the app is published as "Trackhop" (see docs/ROADMAP.md, "Name"): the package id and
the GitHub/F-Droid name stay "Songport". Rather than keeping two copies of every sentence that names
the app, this script copies each main string that says "Songport" into the play source set with the
name swapped, one strings_brand.xml per locale. Strings the play flavour already overrides by hand
(android/app/src/play/res/values*/strings.xml) are left to those files.

    python3 scripts/play_strings.py          # (re)generate
    python3 scripts/play_strings.py --check  # exit 1 if the generated files are stale (CI)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAIN = ROOT / "android/app/src/main/res"
PLAY = ROOT / "android/app/src/play/res"
SRC, DST = "Songport", "Trackhop"
OUT = "strings_brand.xml"
HEADER = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- GENERATED by scripts/play_strings.py: the main strings that name the app, for the Google Play\n"
    "     brand. Do not edit; change the main strings.xml and run the script. -->\n"
    "<resources>\n"
)
STRING = re.compile(r'<string name="([^"]+)"([^>]*)>(.*?)</string>', re.S)


def strings(path: Path):
    """name -> (attributes, body) for every <string> in the file."""
    if not path.exists():
        return {}
    return {m.group(1): (m.group(2), m.group(3)) for m in STRING.finditer(path.read_text(encoding="utf-8"))}


def render(locale_dir: str) -> str:
    main = strings(MAIN / locale_dir / "strings.xml")
    hand = strings(PLAY / locale_dir / "strings.xml")
    lines = [HEADER]
    for name, (attrs, body) in main.items():
        if SRC not in body or name in hand or 'translatable="false"' in attrs:
            continue
        lines.append(f'    <string name="{name}"{attrs}>{body.replace(SRC, DST)}</string>\n')
    lines.append("</resources>\n")
    return "".join(lines)


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for d in sorted(p for p in MAIN.iterdir() if p.is_dir() and p.name.startswith("values")):
        if not (d / "strings.xml").exists():
            continue
        out = PLAY / d.name / OUT
        text = render(d.name)
        if text.count("<string ") == 0:
            continue
        if check:
            if not out.exists() or out.read_text(encoding="utf-8") != text:
                stale.append(str(out.relative_to(ROOT)))
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")
            print(f"{out.relative_to(ROOT)}: {text.count('<string ')} strings")
    if stale:
        print("Stale Play brand strings, run: python3 scripts/play_strings.py", file=sys.stderr)
        for s in stale:
            print("  " + s, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
